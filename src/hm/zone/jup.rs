pub fn pool_label(kind: u64) -> &'static str {
    POOLS.get(kind as usize).copied().unwrap_or("unknown")
}

pub fn is_sound_pool(kind: u64) -> bool {
    matches!(
        kind,
        ASSET_SNDASSET
            | ASSET_SOUNDBANK
            | ASSET_SOUNDBANK_TRANSIENT
            | ASSET_SOUNDBANK_LIST
            | ASSET_SOUNDEVENT
            | ASSET_SNDTABLE
    )
}
